/**
 * 開篇敘事（docs/01 §4.7、M26）：新世界第一次登場時顯示一段原創氛圍文字，
 * 純函式、依世界 seed 決定性挑選，不需要額外持久化「有沒有看過」以外的狀態
 * （前端自行用 localStorage 記錄是否已關閉，仿既有的過場動畫略過機制）。
 */
import { Rng } from "./rng";

const WORLD_OPENING_NARRATIVES = [
  "羅盤剛剛校準完畢，星圖上仍有大片留白。你在琥珀灣的碼頭簽下第一份航海日誌——" +
    "從今天起，蒼瀾海域的風向、行情與人心，都要靠自己一步步摸清楚。",
  "港務長在文件上蓋下印記，你的商船正式獲准離港。甲板上的舊帆手告訴你：" +
    "「這片海域待人不薄，但也從不對誰特別客氣。」",
  "海圖商收下最後一筆訂金，把一卷邊角泛黃的海圖交到你手上——標記到此為止，" +
    "剩下的空白，得靠你自己的船隊去填。",
  "碼頭鐘聲敲過正午，新一季的貿易風終於轉向。你站在甲板上望著遠方的水平線，" +
    "蒼瀾海域的七大海域，此刻才真正對你敞開。",
  "老船長在交接旗艦時只留下一句話：「貨要看得懂，人要交得起，海要放在心上。」" +
    "說完便轉身下船，把這艘船與往後的每一段航程，都交給了你。",
] as const;

export function openingNarrativeFor(seed: number): string {
  const rng = new Rng(seed);
  return rng.pick(WORLD_OPENING_NARRATIVES);
}
